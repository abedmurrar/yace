//! What is captured. Each step is a key (`ctrl+p`, `alt+shift+f`, `enter`;
//! see `key_bytes`), or one of:
//!
//! - `type:TEXT` types text; `shell:COMMAND` types a command and Enter
//! - `wait:TEXT` / `gone:TEXT` waits until the screen shows / stops
//!   showing TEXT, then until YACE is idle; `sleep:MS`; `settle`
//! - `shot:NAME:TITLE` writes `NAME.svg`
//! - `rec` starts a recording; `stop:NAME:TITLE` writes `NAME.cast` and
//!   `NAME.anim.svg`
//! - `dump` prints the screen as text (for writing new scenes)
//!
//! YACE runs with the legacy keyboard protocol, so shortcuts that need the
//! enhanced protocol use their documented fallbacks (`F1` for the Command
//! Palette, `Alt+Shift+F` for search, `Alt+\` to split a terminal) or the
//! Command Palette.

