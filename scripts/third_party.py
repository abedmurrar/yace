#!/usr/bin/env python3
"""Generate THIRD_PARTY_LICENSES.md: every crate compiled into the `yace`
binary, with its version, licence, repository and the licence texts it
ships (deduplicated). Run before each release (scripts/release.sh does).
"""
import hashlib, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
target = sys.argv[1] if len(sys.argv) > 1 else subprocess.check_output(
    ["rustc", "-vV"], text=True).split("host: ")[1].split()[0]
meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target], cwd=ROOT))
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
members = [p["id"] for p in meta["packages"] if p["source"] is None]

# Runtime (normal + build) dependencies reachable from workspace members.
seen, stack = set(), list(members)
while stack:
    for d in nodes[stack.pop()]["deps"]:
        if any(k["kind"] in (None, "build") for k in d["dep_kinds"]) and d["pkg"] not in seen:
            seen.add(d["pkg"])
            stack.append(d["pkg"])
crates = sorted((pkgs[i] for i in seen if pkgs[i]["source"] is not None), key=lambda p: (p["name"], p["version"]))

texts = {}  # hash -> (text, [crate names])
rows = []
for p in crates:
    d = os.path.dirname(p["manifest_path"])
    files = sorted(f for f in os.listdir(d) if f.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")))
    refs = []
    for f in files:
        path = os.path.join(d, f)
        if not os.path.isfile(path):
            continue
        t = open(path, encoding="utf-8", errors="replace").read().strip()
        h = hashlib.sha256(t.encode()).hexdigest()[:12]
        texts.setdefault(h, (f, t, []))[2].append(f'{p["name"]} {p["version"]}')
        refs.append(f"[{f}](#t-{h})")
    rows.append((p["name"], p["version"], p.get("license") or "see files", p.get("repository") or "", refs))

out = [
    "# Third-party licences",
    "",
    "YACE is built on the open-source crates listed below. Thank you to their",
    "authors and contributors. Generated by `scripts/third_party.py`; do not",
    "edit by hand.",
    "",
    f"{len(rows)} crates are compiled into the `yace` binary for `{target}`.",
    "",
    "| Crate | Version | Licence | Repository | Licence files |",
    "|---|---|---|---|---|",
]
for name, ver, lic, repo, refs in rows:
    out.append(f"| {name} | {ver} | {lic} | {repo} | {', '.join(refs) or 'none shipped (SPDX: ' + lic + ')'} |")
out += ["", "## Licence texts", ""]
for h, (fname, t, users) in sorted(texts.items(), key=lambda kv: kv[1][2][0]):
    out.append(f'<a id="t-{h}"></a>')
    out.append(f"### {fname} — used by {', '.join(users[:6])}{' and others' if len(users) > 6 else ''}")
    out.append("")
    out.append("```text")
    out.append(t.replace("```", "``​`"))
    out.append("```")
    out.append("")
open(os.path.join(ROOT, "THIRD_PARTY_LICENSES.md"), "w").write("\n".join(out))
missing = [r[0] for r in rows if not r[4]]
print(f"{len(rows)} crates, {len(texts)} distinct licence texts; crates without licence files: {missing or 'none'}")
