#!/usr/bin/env python3
"""Generate THIRD_PARTY_LICENSES.md: every crate compiled into the `yace`
binary, with its version, licence, repository and the licence texts it
ships (deduplicated). Run before each release (scripts/release.sh does).
"""
import hashlib, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
target = sys.argv[1] if len(sys.argv) > 1 else subprocess.check_output(
    ["rustc", "-vV"], text=True).split("host: ")[1].split()[0]
meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target], cwd=ROOT))
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
members = [p["id"] for p in meta["packages"] if p["source"] is None]

# Runtime (normal + build) dependencies reachable from workspace members.
seen, stack = set(), list(members)
while stack:
    for d in nodes[stack.pop()]["deps"]:
        if any(k["kind"] in (None, "build") for k in d["dep_kinds"]) and d["pkg"] not in seen:
            seen.add(d["pkg"])
            stack.append(d["pkg"])
crates = sorted((pkgs[i] for i in seen if pkgs[i]["source"] is not None), key=lambda p: (p["name"], p["version"]))

MIT = """MIT License

Copyright (c) {holders}

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE."""

texts = {}  # hash -> (text, [crate names])
rows = []
for p in crates:
    d = os.path.dirname(p["manifest_path"])
    files = sorted(f for f in os.listdir(d) if f.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")))
    refs = []
    for f in files:
        path = os.path.join(d, f)
        if not os.path.isfile(path):
            continue
        t = open(path, encoding="utf-8", errors="replace").read().strip()
        h = hashlib.sha256(t.encode()).hexdigest()[:12]
        texts.setdefault(h, (f, t, []))[2].append(f'{p["name"]} {p["version"]}')
        refs.append(f"[{f}](#t-{h})")
    lic = p.get("license") or "see files"
    if not refs and "MIT" in lic.replace("OR", " ").split():
        # The crate ships no licence file: reproduce the MIT terms with the
        # copyright holders from its metadata, as the licence requires.
        holders = ", ".join(a.split(" <")[0] for a in p.get("authors") or []) or f'the {p["name"]} authors'
        t = MIT.format(holders=holders)
        h = hashlib.sha256(t.encode()).hexdigest()[:12]
        texts.setdefault(h, ("MIT (from Cargo metadata)", t, []))[2].append(f'{p["name"]} {p["version"]}')
        refs.append(f"[MIT](#t-{h})")
    rows.append((p["name"], p["version"], lic, p.get("repository") or "", refs))

out = [
    "# Third-party licences",
    "",
    "YACE is built on the open-source crates listed below. Thank you to their",
    "authors and contributors. Generated by `scripts/third_party.py`; do not",
    "edit by hand.",
    "",
    f"{len(rows)} crates are compiled into the `yace` binary for `{target}`.",
    "",
    "| Crate | Version | Licence | Repository | Licence files |",
    "|---|---|---|---|---|",
]
for name, ver, lic, repo, refs in rows:
    out.append(f"| {name} | {ver} | {lic} | {repo} | {', '.join(refs) or 'none shipped (SPDX: ' + lic + ')'} |")
# Colour palettes of the built-in themes (crates/yace/themes/*.toml) are
# derived from these MIT-licensed themes; their notices travel with YACE.
PALETTES = [
    ("One Dark", "crates/yace/themes/one-dark.toml", "https://github.com/atom/atom/tree/master/packages/one-dark-syntax", "2014 GitHub Inc."),
    ("One Dark (terminal colours)", "crates/yace/themes/one-dark.toml", "https://github.com/Binaryify/OneDark-Pro", "2016 Binaryify"),
    ("Dracula", "crates/yace/themes/dracula.toml", "https://github.com/dracula/visual-studio-code", "2016 Dracula Theme"),
    ("Catppuccin Mocha", "crates/yace/themes/catppuccin-mocha.toml", "https://github.com/catppuccin/catppuccin", "2021 Catppuccin"),
    ("Tokyo Night", "crates/yace/themes/tokyo-night.toml", "https://github.com/enkia/tokyo-night-vscode-theme", "2018-present Enkia"),
]
out += [
    "",
    "## Theme palettes",
    "",
    "The colour palettes of these built-in themes are derived from MIT-licensed themes:",
    "",
    "| Theme | File | Source | Licence |",
    "|---|---|---|---|",
]
for name, f, url, holders in PALETTES:
    t = MIT.format(holders=holders)
    h = hashlib.sha256(t.encode()).hexdigest()[:12]
    texts.setdefault(h, ("MIT", t, []))[2].append(f"{name} palette")
    out.append(f"| {name} | `{f}` | {url} | [MIT](#t-{h}) |")
out += ["", "## Licence texts", ""]
for h, (fname, t, users) in sorted(texts.items(), key=lambda kv: kv[1][2][0]):
    out.append(f'<a id="t-{h}"></a>')
    out.append(f"### {fname} — used by {', '.join(users[:6])}{' and others' if len(users) > 6 else ''}")
    out.append("")
    out.append("```text")
    out.append(t.replace("```", "``​`"))
    out.append("```")
    out.append("")
open(os.path.join(ROOT, "THIRD_PARTY_LICENSES.md"), "w").write("\n".join(out))
missing = [r[0] for r in rows if not r[4]]
print(f"{len(rows)} crates, {len(texts)} distinct licence texts; crates without licence files: {missing or 'none'}")
